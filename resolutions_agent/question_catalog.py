@dataclass(frozen=True)
class ChoiceBlueprint:
    """One playful quiz option and its personalized resolution building blocks."""

    option_id: str
    label: str
    flavor_subtext: str
    emoji_badge: str
    traits: Mapping[str, int]
    resolution_title: str
    resolution_pitch: str
    january_step: str
    victory_signal: str
    forecast_hook: str
    toast_hook: str
    charm: str
    anti_title: str = ""
    anti_body: str = ""


@dataclass(frozen=True)
class PromptBlueprint:
    """One curated question in the 2027 Resolutions question bank."""

    question_id: str
    dimension: str
    dimension_label: str
    prompt: str
    custom_placeholder: str
    options: tuple[ChoiceBlueprint, ...]


