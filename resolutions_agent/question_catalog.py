class AntiRepeatQuestionSelector:
    """Selects unique questions per guest using per-dimension sliding windows."""

    def __init__(self, catalog: Sequence[PromptBlueprint] = QUESTION_CATALOG) -> None:
        self._catalog = list(catalog)
        self._by_id: dict[str, PromptBlueprint] = {q.question_id: q for q in self._catalog}
        self._by_dimension: dict[str, list[PromptBlueprint]] = collections.defaultdict(list)
        for q in self._catalog:
            self._by_dimension[q.dimension].append(q)
        self._recent_by_dimension: dict[str, collections.deque[str]] = {
            dim: collections.deque(maxlen=3) for dim in DIMENSION_SEQUENCE
        }

    @property
    def total_size(self) -> int:
        return len(self._catalog)

    def get_by_id(self, question_id: str) -> PromptBlueprint | None:
        return self._by_id.get(question_id)

    def get_by_dimension(self, dimension: str) -> list[PromptBlueprint]:
        return list(self._by_dimension.get(dimension, []))

    def pick_for_dimension(
        self,
        dimension: str,
        excluded_ids: set[str],
        rng: random.Random,
    ) -> PromptBlueprint:
        pool = self._by_dimension.get(dimension)
        if not pool:
            raise KeyError(f"Unknown dimension: {dimension}")

        recent = self._recent_by_dimension[dimension]
        candidates = [
            q
            for q in pool
            if q.question_id not in excluded_ids and q.question_id not in recent
        ]
        if not candidates:
            candidates = [q for q in pool if q.question_id not in excluded_ids]
        if not candidates:
            candidates = list(pool)

        rng.shuffle(candidates)
        chosen = candidates[0]
        recent.append(chosen.question_id)
        return chosen

    def deal_five_questions(
        self,
        guest_seed: str,
        excluded_ids: Sequence[str] = (),
    ) -> list[PromptBlueprint]:
        excluded = set(excluded_ids)
        digest = hashlib.sha256(guest_seed.encode("utf-8")).hexdigest()
        rng = random.Random(digest)
        return [
            self.pick_for_dimension(dim, excluded, rng) for dim in DIMENSION_SEQUENCE
        ]


default_question_selector = AntiRepeatQuestionSelector()
